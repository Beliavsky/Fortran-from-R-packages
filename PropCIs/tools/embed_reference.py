"""Embed checked-in R oracle tables as portable, deterministic Fortran tests."""
from pathlib import Path
import math
root=Path(__file__).resolve().parents[1]
mapping={'diffpropci.mp':'diffpropci_mp','diffpropci.Wald.mp':'diffpropci_wald_mp','scoreci.mp':'scoreci_mp','oddsratioci.mp':'oddsratioci_mp','midPci':'midpci','diffci.bayes':'diffci_bayes','rrci.bayes':'rrci_bayes','orci.bayes':'orci_bayes','diffci.bayes.hpd':'diffci_bayes_hpd'}
def val(x):
    if x=='Inf': return 'positive_inf'
    if x=='-Inf': return '-positive_inf'
    if x=='NaN': return 'quiet_nan'
    return f'{float(x):.17e}_dp'
lines=['! SPDX-License-Identifier: GPL-2.0-only','! Generated by tools/embed_reference.py from actual R 0.3-0 oracles.','program test_reference','  use propcis','  use, intrinsic :: ieee_arithmetic, only: ieee_value, ieee_quiet_nan, ieee_positive_inf, ieee_is_finite, ieee_is_nan','  implicit none','  type(ci_result) :: ci','  real(dp) :: value, positive_inf, quiet_nan','  integer :: count','  positive_inf = ieee_value(0.0_dp, ieee_positive_inf)','  quiet_nan = ieee_value(0.0_dp, ieee_quiet_nan)','  count = 0']
for i,row in enumerate((root/'test/r_reference.tsv').read_text().splitlines()):
    nm, args, lower, upper, tol,*_=row.split('\t')
    if lower=='ERROR': continue
    aa=args.split(',')
    ff=mapping.get(nm,nm)
    if '.bayes' in nm:
        aa=aa[:9]
        fa=[aa[j] if j<4 else val(aa[j]) for j in range(len(aa))]
    elif nm=='z2stat': fa=[aa[j] if j in [1,3] else val(aa[j]) for j in range(len(aa))]
    elif nm=='limit': fa=[val(x) if j in [4,5] else x for j,x in enumerate(aa)]
    elif nm=='wald2ci': fa=aa[:4]+[val(aa[4]),repr(aa[5])]
    else: fa=aa[:-1]+[val(aa[-1])]
    # Upstream endpoint-roundoff defect is tested analytically in test_properties.
    if nm=='oddsratioci.mp' and aa[0]=='0': continue
    expr=f'{ff}('+', '.join(fa)+')'
    label=f'R case {i+1}: {nm}'
    if nm in ['acceptbin','z2stat','limit']:
        lines += [f'  value = {expr}',f"  call check(value, {val(lower)}, {val(tol)}, '{label}')"]
    else:
        lines += [f'  ci = {expr}',"  if (ci%status /= ci_ok) error stop 'R reference: unexpected status'",f"  call check(ci%lower, {val(lower)}, {val(tol)}, '{label} lower')",f"  call check(ci%upper, {val(upper)}, {val(tol)}, '{label} upper')"]
lines+=['  print *, "Actual R oracle assertions passed:", count','contains', '''  subroutine check(actual, expected, tolerance, label)
    real(dp), intent(in) :: actual !! Computed scalar bound or statistic.
    real(dp), intent(in) :: expected !! Actual R reference value, possibly infinite or NaN.
    real(dp), intent(in) :: tolerance !! Absolute-relative tolerance scaled by max(1,abs(expected)).
    character(len=*), intent(in) :: label !! Oracle case identifier for failure reporting.
    logical :: ok
    count = count + 1
    if (ieee_is_nan(expected)) then
      ok = ieee_is_nan(actual)
    else if (.not. ieee_is_finite(expected)) then
      ok = actual == expected
    else
      ok = ieee_is_finite(actual)
      if (ok) ok = abs(actual - expected) <= tolerance * max(1.0_dp, abs(expected))
    end if
    if (.not. ok) then
      print *, label, actual, expected
      error stop 'Actual R oracle mismatch'
    end if
  end subroutine check
end program test_reference''']
(root/'test/test_reference.f90').write_text('\n'.join(lines)+'\n')
lines=['! SPDX-License-Identifier: GPL-2.0-only','! Generated from independently inverted R beta-product distributions.','program test_bayesian_reference','  use propcis','  use, intrinsic :: ieee_arithmetic, only: ieee_is_finite','  implicit none','  type(ci_result) :: ci','  real(dp) :: shapes(4), lower, upper, cdf1, cdf2','  integer :: status, count','  count = 0']
for i,row in enumerate((root/'test/independent_reference.tsv').read_text().splitlines()):
    aa=row.split('\t');kind=int(aa[0]);sh=aa[1:5];lo,hi=aa[5:]
    lines += ['  shapes = [ &','    '+', '.join(val(x) for x in sh)+' ]','  ci = '+['diffci_bayes','rrci_bayes','orci_bayes'][kind-1]+'(0, 0, 0, 0, shapes(1), shapes(2), shapes(3), shapes(4))',f'  lower = {val(lo)}',f'  upper = {val(hi)}',f"  call check(ci, lower, upper, 'Independent posterior case {i+1}')",f'  cdf1 = bayes_cdf({kind}, ci%lower, shapes, status)',"  if (status /= ci_ok) error stop 'lower CDF status'",f'  cdf2 = bayes_cdf({kind}, ci%upper, shapes, status, upper_tail=.true.)',"  if (status /= ci_ok) error stop 'upper CDF status'","  if (abs(cdf1 - 0.025_dp) > 2.0e-7_dp .or. abs(cdf2 - 0.025_dp) > 2.0e-7_dp) error stop 'posterior tail mass'"]
lines += ['  print *, "Independent posterior assertions passed:", count','contains', '''  subroutine check(actual, lo, hi, label)
    type(ci_result), intent(in) :: actual !! Computed equal-tail posterior interval and numerical status.
    real(dp), intent(in) :: lo !! Independent lower quantile from R integrate plus uniroot.
    real(dp), intent(in) :: hi !! Independent upper quantile from R integrate plus uniroot.
    character(len=*), intent(in) :: label !! Posterior reference case identifier.
    count = count + 1
    if (actual%status /= ci_ok .or. .not. ieee_is_finite(actual%lower) .or. .not. ieee_is_finite(actual%upper)) then
      print *, label, actual
      error stop 'Independent posterior status'
    end if
    if (abs(actual%lower - lo) > 2.0e-6_dp * max(abs(lo), 1.0e-14_dp) .or. &
        abs(actual%upper - hi) > 2.0e-6_dp * max(abs(hi), 1.0e-14_dp)) then
      print *, label, actual%lower, lo, actual%upper, hi
      error stop 'Independent posterior quantiles'
    end if
  end subroutine check
end program test_bayesian_reference''']
(root/'test/test_bayesian_reference.f90').write_text('\n'.join(lines)+'\n')
