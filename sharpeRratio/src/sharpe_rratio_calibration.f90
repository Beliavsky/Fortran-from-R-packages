   pure function spline_value(x, knots, values, bcoef, ccoef, dcoef) result(value)
      real(dp), intent(in) :: x
      real(dp), intent(in) :: knots(:), values(:), bcoef(:), ccoef(:), dcoef(:)
      real(dp) :: value, dx
      integer :: lo, hi, mid, idx, n

      n = size(knots)
      if (x <= knots(1)) then
         idx = 1
      else if (x >= knots(n)) then
         idx = n
      else
         lo = 1
         hi = n
         do while (hi-lo > 1)
            mid = (lo+hi)/2
            if (x < knots(mid)) then
               hi = mid
            else
               lo = mid
            end if
         end do
         idx = lo
      end if
      dx = x-knots(idx)
      value = values(idx)+dx*(bcoef(idx)+dx*(ccoef(idx)+dx*dcoef(idx)))
   end function spline_value

   pure function calibration_a(x) result(value)
      real(dp), intent(in) :: x
      real(dp) :: value
