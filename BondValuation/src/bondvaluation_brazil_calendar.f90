  logical function is_nonbusiness_brazil(serial_day) result(ans)
    integer, intent(in) :: serial_day
    integer :: j, iw, ib
    call initialize_calendar()
    if (serial_day < brazil_calendar_start .or. serial_day > brazil_calendar_end) then
      ans = .false.
      return
    end if
    j = serial_day - brazil_calendar_start
    iw = j / 64 + 1
    ib = modulo(j, 64)
    ans = btest(nonbusiness_bits(iw), ib)
  end function is_nonbusiness_brazil

  integer function count_nonbusiness_brazil(first_serial, last_serial) result(n)
    integer, intent(in) :: first_serial, last_serial
    integer :: s
    call initialize_calendar()
    n = 0
    do s = first_serial, last_serial - 1
      if (is_nonbusiness_brazil(s)) n = n + 1
    end do
  end function count_nonbusiness_brazil
