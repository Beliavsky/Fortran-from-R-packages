# Run from PRROC/: Rscript tools/generate_reference.R
# Numerical oracle: preserved, unmodified CRAN PRROC 1.4 source.
source('upstream/R/PRROC.R')
stopifnot(read.dcf('upstream/DESCRIPTION')[1, 'Version'] == '1.4')
options(digits = 17)
out <- file('test/test_r_reference.f90', 'w')
emit <- function(...) writeLines(paste0(...), out)
num <- function(x) paste0(sprintf('%.17e', x), '_dp')
array <- function(x) {
  if (length(x) == 0) return('[real(dp) ::]')
  paste0('[ &\n', paste(sapply(split(num(x), ceiling(seq_along(x) / 3)), function(v)
    paste0('         ', paste(v, collapse = ', '))), collapse = ', &\n'), ' ]')
}
emit('! SPDX-License-Identifier: GPL-3.0-only')
emit('! Generated by tools/generate_reference.R from CRAN PRROC 1.4.')
emit('program test_r_reference\n   use prroc_api\n   use, intrinsic :: ieee_arithmetic, only : ieee_is_nan\n   implicit none')
emit('   type(prroc_result) :: actual\n   integer :: status, checks\n   checks = 0')
cases <- list(
  list(name = 'perfect', scores.class0 = c(3, 4), scores.class1 = c(0, 1)),
  list(name = 'reverse', scores.class0 = c(0, 0), scores.class1 = c(1, 1)),
  list(name = 'mixed_ties', scores.class0 = c(4, 3, 3, 1), scores.class1 = c(3, 2, 1, 0)),
  list(name = 'identical_classes', scores.class0 = c(1, 2, 3), scores.class1 = c(3, 1, 2)),
  list(name = 'binary', scores.class0 = c(4, 4, 2, 1, 0), weights.class0 = c(1, 0, 1, 1, 0)),
  list(name = 'soft_ties', scores.class0 = c(4, 4, 2, 1), weights.class0 = c(.2, .9, .7, .1)),
  list(name = 'weighted', scores.class0 = c(5, 3, 1), scores.class1 = c(4, 3, 0),
       weights.class0 = c(3, 2, 1), weights.class1 = c(2, 5, 4)),
  list(name = 'asymmetric', scores.class0 = c(3, 1), scores.class1 = c(4, 2, 0),
       weights.class0 = c(.25, .8), weights.class1 = c(.2, .6, .4)),
  list(name = 'second_weight_only', scores.class0 = c(3, 1), scores.class1 = c(2, 0),
       weights.class1 = c(.2, .4)),
  list(name = 'single_tie', scores.class0 = c(0, 0), scores.class1 = c(0, 0, 0)),
  list(name = 'imbalanced', scores.class0 = 2, scores.class1 = seq(0, 4, length.out = 15)),
  list(name = 'independent_same_scores', scores.class0 = c(4, 2, 1), scores.class1 = c(4, 2, 1),
       weights.class0 = c(5, .5, 1), weights.class1 = c(1, 3, 2)),
  list(name = 'one_class', scores.class0 = c(4, 3, 1), weights.class0 = c(1, 1, 1)),
  list(name = 'default_unweighted', scores.class0 = c(3, 3, 1), scores.class1 = c(4, 2), default_step = TRUE),
  list(name = 'default_soft', scores.class0 = c(4, 4, 2, 1), weights.class0 = c(.2, .9, .7, .1),
       default_step = TRUE),
  list(name = 'zero_tail', scores.class0 = c(2, -9), scores.class1 = c(1, -8),
       weights.class0 = c(1, 0), weights.class1 = c(1, 0)),
  list(name = 'lazy_default', scores.class0 = c(2, 1), scores.class1 = c(3, 0),
       weights.class0 = c(.2, .8)),
  list(name = 'lazy_scores', scores.class0 = c(2, 1), weights.class0 = c(.2, .8),
       weights.class1 = c(.3, .7)),
  list(name = 'sorted', scores.class0 = c(1, 2, 4), scores.class1 = c(0, 2, 3), sorted = TRUE)
)
# Deterministic randomized corpus with a local RNG seed; no RNG is translated.
set.seed(72215)
for (i in 1:16) cases[[length(cases) + 1]] <- list(name = paste0('random_soft_', i),
  scores.class0 = sample(-3:3, 8, replace = TRUE), weights.class0 = runif(8, .02, .98))
for (i in 1:8) cases[[length(cases) + 1]] <- list(name = paste0('random_hard_', i),
  scores.class0 = sample(-3:3, 7, replace = TRUE), scores.class1 = sample(-3:3, 9, replace = TRUE))
for (case in cases) {
  name <- case$name
  args <- case[!names(case) %in% c('name', 'default_step')]
  default_step <- isTRUE(case$default_step)
  for (is_pr in c(TRUE, FALSE)) {
    if (name == 'one_class' && !is_pr) next
    f <- if (is_pr) pr.curve else roc.curve
    callargs <- c(args, list(curve = TRUE, max.compute = TRUE, min.compute = TRUE, rand.compute = TRUE))
    if (is_pr && !default_step) callargs$minStepSize <- .35
    ref <- suppressWarnings(do.call(f, callargs))
    emit('   ! ', name, if (is_pr) ' PR' else ' ROC')
    emit('   call ', if (is_pr) 'pr_curve' else 'roc_curve', '( &')
    callparts <- c(paste0('scores_class0 = ', array(args$scores.class0)), 'result = actual')
    for (key in c('scores.class1', 'weights.class0', 'weights.class1')) {
      if (!is.null(args[[key]])) callparts <- c(callparts, paste0(gsub('\\.', '_', key), ' = ', array(args[[key]])))
    }
    if (isTRUE(args$sorted)) callparts <- c(callparts, 'sorted = .true.')
    if (is_pr && !default_step) callparts <- c(callparts, 'min_step_size = 0.35_dp')
    callparts <- c(callparts, 'curve = .true.', 'max_compute = .true.', 'min_compute = .true.',
                   'rand_compute = .true.', 'status = status')
    emit(paste0('      ', paste(callparts, collapse = ', &\n      '), ')'))
    emit('   if (status /= prroc_ok) error stop "oracle status: ', name, '"')
    for (part in c('main', 'max', 'min', 'rand')) {
      # R recycles unequal weight vectors in the random baseline denominator.
      # This translation uses actual prevalence; independent tests cover the correction.
      if (name == 'asymmetric' && part == 'rand' && is_pr) next
      r <- if (part == 'main') ref else ref[[part]]
      target <- switch(part, main = 'actual', max = 'actual%maximum', min = 'actual%minimum', rand = 'actual%random')
      auc <- if (is_pr) r$auc.integral else r$auc
      emit('   call close_scalar(', target, '%auc, ', num(auc), ', checks)')
      if (is_pr) {
        if (is.na(r$auc.davis.goadrich)) emit('   if (.not. ieee_is_nan(', target, '%auc_davis_goadrich)) error stop "DG eligibility"')
        else emit('   call close_scalar(', target, '%auc_davis_goadrich, ', num(r$auc.davis.goadrich), ', checks)')
      }
      points <- r$curve[complete.cases(r$curve), , drop = FALSE]
      # One-class reference curves retain a zero-mass threshold in upstream; the translation omits it.
      if (name %in% c('one_class', 'zero_tail') && part != 'rand') next
      emit('   call close_curve(', target, '%curve, reshape(', array(as.vector(points)), ', [', nrow(points), ', 3]), checks)')
    }
  }
}
emit('   print *, "PRROC R-reference assertions:", checks\ncontains')
emit('   subroutine close_scalar(actual, expected, checks)')
emit('      real(dp), intent(in) :: actual !! Scalar produced by the Fortran implementation.')
emit('      real(dp), intent(in) :: expected !! Numeric oracle from preserved PRROC 1.4 R source.')
emit('      integer, intent(inout) :: checks !! Running number of successful numeric assertions.')
emit('      if (ieee_is_nan(actual) .or. abs(actual - expected) > 2.0e-12_dp) then')
emit('         print *, "Scalar mismatch:", actual, expected\n         error stop "R scalar oracle"\n      end if')
emit('      checks = checks + 1\n   end subroutine close_scalar')
emit('   subroutine close_curve(actual, expected, checks)')
emit('      real(dp), intent(in) :: actual(:,:) !! Observed Fortran curve matrix with three columns.')
emit('      real(dp), intent(in) :: expected(:,:) !! Upstream matrix with unused all-NA padding removed.')
emit('      integer, intent(inout) :: checks !! Running number of successful matrix assertions.')
emit('      if (any(shape(actual) /= shape(expected))) then')
emit('         print *, "Curve shape mismatch:", shape(actual), shape(expected)\n         error stop "R curve shape"\n      end if')
emit('      if (any(ieee_is_nan(actual)) .or. any(abs(actual - expected) > 3.0e-12_dp)) then')
emit('         print *, "Curve max error:", maxval(abs(actual - expected))\n         error stop "R curve oracle"\n      end if')
emit('      checks = checks + 1\n   end subroutine close_curve\nend program test_r_reference')
close(out)
cat('Generated', length(cases), 'R cases in test/test_r_reference.f90\n')
