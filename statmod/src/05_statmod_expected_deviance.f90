pure subroutine expected_deviance_binomial(prob,nsize,m,v)
real(dp),intent(in)::prob
integer,intent(in)::nsize
real(dp),intent(out)::m,v
real(dp)::pp,mu,logpp,dd,pr,de,a,k
integer::j
pp=min(prob,1-prob)
mu=pp*nsize
if(mu<low_bound) then
m=0
v=0
return
end if
if(nsize<2) then
   m=-2*(pp*log(pp)+(1-pp)*log(1-pp))
   logpp=log((1-pp)/pp)
   v=4*pp*(1-pp)*logpp**2
   return
end if
if(nsize<200) then
   dd=0
   do j=0,nsize
      pr=dbinom(real(j,dp),nsize,pp)
      if(j==0) then
      de=2*nsize*log(1/(1-pp))
      else if(j==nsize) then
      de=2*nsize*log(1/pp)
      else
      de=2*(j*log(real(j,dp)/mu)+(nsize-j)*log(real(nsize-j,dp)/(nsize-mu)))
      end if
      dd=dd+pr*de
   end do
   m=dd
   v=0
   do j=0,nsize
      pr=dbinom(real(j,dp),nsize,pp)
      if(j==0) then
      de=2*nsize*log(1/(1-pp))
      else if(j==nsize) then
      de=2*nsize*log(1/pp)
      else
      de=2*(j*log(real(j,dp)/mu)+(nsize-j)*log(real(nsize-j,dp)/(nsize-mu)))
      end if
      v=v+pr*(de-dd)**2
   end do
else
   a=pois_alpha(mu)
   k=pois_kappa(mu)
   m=k/a
   v=2*k/(a*a)
end if
end subroutine

