pure subroutine expected_deviance_nbinom(mu,size,m,v)
real(dp),intent(in)::mu,size
real(dp),intent(out)::m,v
real(dp)::phi,a,k,pr,de,dd
integer::j,n
if(mu<low_bound)then
m=0
v=0
return
end if
phi=1/size
if(phi<sweet_cutoff1)then
a=anbinomdevc_1(mu,phi)
k=knbinomdevc_1(mu,phi)
m=k/a
v=2*k/(a*a)
return
end if
if(phi<sweet_cutoff2)then
a=anbinomdevc_2(mu,phi)
k=knbinomdevc_2(mu,phi)
m=k/a
v=2*k/(a*a)
return
end if
n=max(1,int(mu*mu/size+10))
dd=0
do j=0,n-1
   pr=dnbinom_mu_real(j,size,mu)
   if(j==0)then
   de=2*(-size*log(size/(mu+size)))
   else
   de=2*(j*log(real(j,dp)/mu)-(j+size)*log((j+size)/(mu+size)))
   end if
   dd=dd+pr*de
end do
m=dd
v=0
do j=0,n-1
   pr=dnbinom_mu_real(j,size,mu)
   if(j==0)then
   de=2*(-size*log(size/(mu+size)))
   else
   de=2*(j*log(real(j,dp)/mu)-(j+size)*log((j+size)/(mu+size)))
   end if
   v=v+pr*(de-dd)**2
end do
end subroutine

pure subroutine expected_deviance(mu,family,param,m,v)
real(dp),intent(in)::mu
character(len=*),intent(in)::family
real(dp),intent(in),optional::param
real(dp),intent(out)::m,v
real(dp)::s
select case(trim(family))
case('gaussian','inverse.gaussian')
m=1
v=2
case('poisson','Poisson');call expected_deviance_poisson(min(mu,1.0e7_dp),m,v)
case('Gamma','gamma')
   s=1
   if(present(param))s=param
   m=meanval_digamma(-s)*s
   v=2*d2cumulant_digamma(-s)*s*s
case('negative.binomial')
   s=1
   if(present(param))s=param
   if(s>1.0e7_dp)then
      call expected_deviance_poisson(min(mu,1.0e7_dp),m,v)
   else
      ! Match expectedDeviance.R limit.size guard against enormous direct sums.
      if(s<=0.25_dp) s=max(s,min(mu*mu/(1.0e5_dp-10.0_dp),0.25_dp)+1.0e-10_dp)
      call expected_deviance_nbinom(min(mu,1.0e7_dp),min(s,1.0e7_dp),m,v)
   end if
case default
   m=0
   v=0
end select
end subroutine

