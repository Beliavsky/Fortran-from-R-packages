emit <- function(...) source_lines <<- c(source_lines, ...)
literal <- function(x) {
  if(is.na(x)) return("q")
  if(!is.finite(x)) stop("Infinite oracle requires an explicit test")
  paste0(sprintf("%.17e", x), "_dp")
}
array_lines <- function(x, end="]") {
  lit <- vapply(as.numeric(x), literal, character(1))
  groups <- split(lit, ceiling(seq_along(lit)/3))
  out <- vapply(groups, paste, character(1), collapse=", ")
  if(length(out)>1) out[-length(out)] <- paste0(out[-length(out)], ", &")
  out[length(out)] <- paste0(out[length(out)], end)
  paste0("      ",out)
}
for(name in c("x","hl","ohlc","hlna","xna","trend","splits","dividends","ra","rb")) {
  value <- get(name)
  if(is.matrix(value)) {
    emit(paste0("   ",name," = reshape([ &"), array_lines(value,
      paste0("], [",nrow(value),", ",ncol(value),"] )")))
  } else {
    emit(paste0("   ",name," = [ &"), array_lines(value))
  }
}
reference <- function(call, value, label) {
  routine <- if(is.matrix(value)) "check2" else "check1"
  emit(paste0("   call ",routine,"(",call,", [ &"), array_lines(value,
    paste0("], '",label,"')")))
}
