   subroutine check1(actual, expected, label)
      real(dp), intent(in) :: actual(:) !! Computed chronological indicator values.
      real(dp), intent(in) :: expected(:) !! TTR 0.24.4 reference values with NaNs for missing observations.
      character(*), intent(in) :: label !! Identifies the computation in failure diagnostics.
      integer :: j
      if (size(actual) /= size(expected)) error stop 'reference shape mismatch'
      do j = 1, size(expected)
         if (ieee_is_nan(expected(j))) then
            if (.not. ieee_is_nan(actual(j))) then
               print *, label, j, 'expected NaN, received ', actual(j)
               error stop 'missingness mismatch'
            end if
         else
            if (.not. ieee_is_finite(actual(j))) then
               print *, label, j, 'unexpected nonfinite value'
               error stop 'nonfinite result'
            end if
            if (abs(actual(j) - expected(j)) > 5.0e-11_dp * max(1.0_dp, abs(expected(j)))) then
               print *, label, j, actual(j), expected(j)
               error stop 'reference value mismatch'
            end if
         end if
         checked = checked + 1
      end do
   end subroutine
   subroutine check2(actual, expected, label)
      real(dp), intent(in) :: actual(:, :) !! Computed indicator matrix, rows chronological and columns documented.
