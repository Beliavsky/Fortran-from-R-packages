  function qmf(g, low_to_high) result(h)
    real(dp), intent(in) :: g(:)
    logical, intent(in), optional :: low_to_high
    real(dp), allocatable :: h(:)
    logical :: l2h
    integer :: i, n
    n = size(g)
    allocate(h(n))
    l2h = .true.
    if (present(low_to_high)) l2h = low_to_high
    if (l2h) then
      do i = 1, n
      h(i) = (-1.0_dp)**real(i-1,dp) * g(n-i+1)
      end do
    else
      do i = 1, n
      h(i) = (-1.0_dp)**real(i,dp) * g(n-i+1)
      end do
    end if
  end function qmf

