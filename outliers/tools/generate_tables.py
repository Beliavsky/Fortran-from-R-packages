"""Regenerate the verbatim numeric tables from the preserved GPL-2.0-or-later R source."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
text = '''! SPDX-License-Identifier: GPL-2.0-or-later
! Tables from outliers 0.15, Lukasz Komsta. See NOTICE.md.
! Generated by tools/generate_tables.py. Upstream anomalies are preserved.
module outliers_tables
   use r_kinds, only : dp
   implicit none
   private
   public :: dixon_probabilities, dixon_tables, grubbs_probabilities, grubbs_table
'''
def extract(path,name):
    src = path.read_text()
    return [v.strip() for v in re.search(r'\b'+name+r'\s*<-\s*c\((.*?)\);',src,re.S).group(1).split(',')]
def emit(name,values,shape):
    global text
    rank = ','.join(map(str,shape))
    text += f'   real(dp), parameter :: {name}({rank}) = reshape([ &\n'
    tokens = [('0.0' if v == 'NA' else v if '.' in v or 'e' in v else v+'.0')+'_dp' for v in values]
    for i in range(0,len(tokens),6):
        text += '      '+', '.join(tokens[i:i+6])+(', &' if i+6<len(tokens) else ' &')+'\n'
    text += f'      ], [{rank}])\n'
d = root/'upstream/R/qdixon.R'
g = root/'upstream/R/qgrubbs.R'
emit('dixon_probabilities',extract(d,'pp'),[15])
emit('dixon_tables',sum((extract(d,'q'+str(t)) for t in [10,11,12,20,21,22]),[]),[15,30,6])
emit('grubbs_probabilities',extract(g,'pp'),[13])
emit('grubbs_table',extract(g,'gtwo'),[13,30])
text += 'end module outliers_tables\n'
(root/'src/outliers_tables.f90').write_text(text)
