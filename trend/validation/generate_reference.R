# Run from trend/: Rscript validation/generate_reference.R
# Actual pinned trend 1.1.8 public functions and its registered Monte Carlo kernels.
library(trend)
stopifnot(as.character(packageVersion('trend')) == '1.1.8')
options(warn = 1)
x <- c(8,3,5,1,9,2,7,4,12,10,6,11)
y <- c(4,7,2,10,3,11,9,8,1,5,12,6)
tied <- c(8,3,5,1,9,2,7,4,12,10,6,10)
season <- as.vector(rbind(x, y + 0.3 * seq_along(y)))
long <- sin(seq_len(120)*1.71) + cos(seq_len(120)*0.42) + seq_len(120)*0.003
con <- file('test/r_reference.f90', 'w')
writeLines(c('! SPDX-License-Identifier: GPL-3.0-only',
  '! Generated by validation/generate_reference.R using actual trend 1.1.8.',
  'module trend_r_reference','   use r_kinds, only : dp','   implicit none'), con)
emit <- function(name, v) {
  v <- as.numeric(v)
  values <- ifelse(is.nan(v) | is.na(v), '0.0_dp', sprintf('%.17e_dp', v))
  writeLines(sprintf('   real(dp), parameter :: %s(%d) = [ &',name,length(v)),con)
  for (i in seq(1,length(v),by=3)) {
    end <- min(length(v),i+2)
    writeLines(paste0('      ',paste(values[i:end],collapse=', '),if(end<length(v)) ', &' else ' ]'), con)
  }
}
base <- function(a) c(a$statistic, a$p.value)
mkfields <- function(a) c(base(a), a$estimates)
emit('rx',x)
emit('ry',y)
emit('rtied',tied)
emit('rseason',season)
emit('rlong',long)
for (side in c('two.sided','greater','less')) {
  tag <- gsub('\\.','_',side)
  emit(paste0('ref_mk_',tag),mkfields(mk.test(x,alternative=side)))
  emit(paste0('ref_rrod_',tag),base(rrod.test(x[1:6],y[7:12],alternative=side)))
  emit(paste0('ref_partial_mk_',tag),mkfields(partial.mk.test(x,y,alternative=side)))
}
emit('ref_mk_ties',mkfields(mk.test(tied,continuity=FALSE)))
slope <- sens.slope(x)
emit('ref_slope',c(base(slope),slope$estimates,slope$conf.int))
emit('ref_sea_slope',sea.sens.slope(ts(season,frequency=2)))
for (odd in c(FALSE, TRUE)) {
  a <- itam(if (odd) x[-12] else x, conf.level=0.9)
  emit(paste0('ref_itam_',if(odd) 'odd' else 'even'),c(base(a),a$estimates,a$conf.int,as.matrix(a$df)))
}
smk <- smk.test(ts(season,frequency=2))
emit('ref_smk',c(mkfields(smk),smk$Sg,smk$varSg,smk$Zg,smk$pvalg,smk$taug))
smk2 <- smk.test(ts(season[-24],frequency=2),continuity=FALSE,alternative='greater')
emit('ref_smk_incomplete',c(mkfields(smk2),smk2$Sg,smk2$varSg,smk2$Zg,smk2$pvalg,smk2$taug))
mult <- mult.mk.test(ts(cbind(x,y)))
emit('ref_mult',c(mkfields(mult),mult$cov))
multshort <- suppressWarnings(mult.mk.test(ts(cbind(x[1:8],y[1:8]))))
emit('ref_mult_short',c(mkfields(multshort),multshort$cov))
csmk <- csmk.test(ts(season,frequency=2))
emit('ref_csmk',c(mkfields(csmk),csmk$cov))
for (method in c('pearson','spearman')) {
  a <- partial.cor.trend.test(tied,y,method=method)
  emit(paste0('ref_partial_cor_',method),c(base(a),a$estimate,a$cor))
}
emit('ref_bartels',base(bartels.test(x)))
emit('ref_bartels_long',base(bartels.test(long)))
emit('ref_cs',base(cs.test(x)))
emit('ref_cs_long',base(cs.test(long)))
emit('ref_wm',base(wm.test(x)))
emit('ref_wm_long',base(wm.test(long)))
emit('ref_ww',base(ww.test(x)))
emit('ref_ww_long',base(ww.test(long)))
a <- pettitt.test(tied)
emit('ref_pettitt',c(base(a),a$estimate,a$data))
for (method in c('wilcox.test','rrod.test')) {
  a <- lanzante.test(x,method=method)
  emit(paste0('ref_lanzante_',sub('\\.test','',method)),c(base(a),a$estimate,a$data))
}
a <- suppressWarnings(lanzante.test(tied))
emit('ref_lanzante_ties',c(base(a),a$estimate,a$data))
for (fun in c('br.test','bu.test','snh.test')) {
  set.seed(20261011)
  a <- get(fun)(x,m=64)
  emit(paste0('ref_',sub('\\.test','',fun)),c(base(a),a$estimate,a$data))
  set.seed(7781)
  a <- get(fun)(x,m=50000)
  emit(paste0('ref_',sub('\\.test','',fun),'_large_mc'),a$p.value)
}
set.seed(20261011)
null <- matrix(rnorm(12*64),12,64)
writeLines(c('contains','   pure function reference_null() result(samples)',
  '      real(dp) :: samples(12,64)'),con)
for (col in seq(1,64,by=8)) {
  values <- sprintf('%.17e_dp',as.numeric(null[,col:(col+7)]))
  writeLines(sprintf('      samples(:, %d:%d) = reshape([ &',col,col+7),con)
  for (i in seq(1,length(values),by=3)) {
    end <- min(length(values),i+2)
    writeLines(paste0('         ',paste(values[i:end],collapse=', '),if(end<length(values)) ', &' else ' ], [12,8])'),con)
  }
}
writeLines(c('   end function reference_null','end module trend_r_reference'),con)
close(con)
writeLines(capture.output(sessionInfo()),'validation/R-session.txt')
