# Generates genuine NetworkRiskMeasures 0.1.7 numerical oracles.
# Run from package root: Rscript reference/generate_reference.R
suppressPackageStartupMessages(library(NetworkRiskMeasures))
stopifnot(as.character(packageVersion('NetworkRiskMeasures')) == '0.1.7')
options(digits=17)
a <- matrix(c(0,10,3,1,0,2,0,3,0),3)
dimnames(a) <- list(letters[1:3],letters[1:3])
b <- c(2,5,2)
w <- c(10,100,30)
v <- matrix(c(0,0.2,0.1,0,0.7,0,0.4,0,0,0.6,0,0,0,0,0,0),4)
dimnames(v) <- list(letters[1:4],letters[1:4])
shocks <- list(c(0.4,0,0,0),c(0,0.6,0,0.1),c(1,0,0,0))
refs <- list()
refs$risk_assets <- risk_matrix(a,b)
refs$risk_liabilities <- risk_matrix(a,b,exposure_type='liabilities')
refs$vulnerability <- vulnerability_matrix(a,b)
refs$criticality <- criticality(a,b)
refs$comm_full <- as.matrix(communicability_matrix(v))
refs$comm_three <- as.matrix(communicability_matrix(v,terms=3,sparse=FALSE))
refs$susceptibility <- impact_susceptibility(a,b)
refs$weighted_susceptibility <- impact_susceptibility(a,b,weights=w,binary=FALSE)
refs$fluidity <- impact_fluidity(a,b)
refs$weighted_fluidity <- impact_fluidity(a,b,weights=w,binary=FALSE,terms=7)
refs$diffusion <- as.matrix(impact_diffusion(a,b)[,-1])
refs$weighted_diffusion <- as.matrix(impact_diffusion(a,b,weights=w,binary=FALSE)[,-1])
for (method in c('debtrank','single','threshold')) {
  choice <- if (method=='single') 'debtrank' else method
  args <- list(exposures=v,buffer=c(2,3,5,7),shock=shocks,weights=c(1,2,3,4),method=choice,
      exposure_type='impact',keep.history=TRUE,abs.tol=1e-12,max.it=1000,verbose=FALSE)
  if(method=='threshold') args$alpha <- 0.5 else args$single.hit <- (method=='single')
  fit <- do.call(contagion,args)
  refs[[paste0(method,'_final')]] <- sapply(fit$simulations,`[[`,'st')
  refs[[paste0(method,'_summary')]] <- t(as.matrix(summary(fit)$summary_table[,-1]))
  refs[[paste0(method,'_iterations')]] <- sapply(fit$simulations,function(x) length(x$s))
}
rows <- c(7,5,3,1,3,0,1)
cols <- c(4,5,5,0,0,2,4)
refs$max_ent <- max_ent(rows,cols,abs.tol=1e-10,verbose=FALSE)
refs$matrix_estimation <- matrix_estimation(rows,cols,abs.tol=1e-10,verbose=FALSE)
# Controlled-draw reference: retain the exact upstream min_dens function body,
# replacing only its three random-draw entry points. This is not R RNG parity.
stream <- ((seq_len(10000)*37) %% 997)/997
cursor <- 0L
next_draw <- function() {
  cursor <<- cursor+1L
  if(cursor>length(stream)) stop('reference uniform stream exhausted')
  stream[cursor]
}
rng <- new.env(parent=asNamespace('NetworkRiskMeasures'))
rng$runif <- function(n) { stopifnot(n==1); next_draw() }
rng$sample.int <- function(n,size,prob=NULL) {
  stopifnot(size==1)
  u <- next_draw()
  if(is.null(prob)) return(min(n,1L+floor(n*u)))
  p <- prob/sum(prob)
  which(cumsum(p)>u)[1]
}
rng$sample <- function(x,size) { stopifnot(size==1); x[min(length(x),1L+floor(length(x)*next_draw()))] }
md <- getExportedValue('NetworkRiskMeasures','min_dens')
environment(md) <- rng
refs$min_dens_controlled <- md(rows,cols,c=0.3,lambda=0.7,k=20,remove.prob=0.08,
    abs.tol=1e-10,max.it=10000,verbose=FALSE)
refs$min_dens_draws <- cursor
# Preserve a standard-R seeded result separately, as genuine R stochastic evidence.
set.seed(192)
standard_md <- min_dens(rows,cols,verbose=FALSE)
write.table(standard_md,'reference/r_standard_seed192.txt',row.names=FALSE,col.names=FALSE)
stopifnot(max(abs(rowSums(standard_md)-rows))<1e-3, max(abs(colSums(standard_md)-cols))<1e-3)
fmt <- function(x) paste0(sprintf('%.17e',as.numeric(x)),'_dp')
lines <- c('! SPDX-License-Identifier: GPL-3.0-only',
 '! Generated by reference/generate_reference.R from NetworkRiskMeasures 0.1.7.',
 'module network_reference_values','   use r_kinds, only: dp','   implicit none')
for(name in names(refs)) {
  vals <- fmt(refs[[name]])
  lines <- c(lines,paste0('   real(dp), parameter :: ref_',name,'(',length(vals),') = [ &'))
  for(i in seq(1,length(vals),by=3)) {
    group <- paste(vals[i:min(i+2,length(vals))],collapse=', ')
    suffix <- if(i+2>=length(vals)) ' ]' else ', &'
    lines <- c(lines,paste0('      ',group,suffix))
  }
}
lines <- c(lines,'end module network_reference_values')
writeLines(lines,'test/network_reference_values.f90')
sink('reference/session-info.txt')
print(sessionInfo())
cat('\nControlled minimum-density draws:',cursor,'\n')
cat('All nonstochastic oracle values use unchanged installed R package code.\n')
sink()
