# Run from the package root with infotheo 1.2.0.1 installed:
# Rscript tools/generate_reference.R > test/r_reference_data.f90
suppressPackageStartupMessages(library(infotheo))
stopifnot(as.character(packageVersion('infotheo')) == '1.2.0.1')
x <- cbind(c(0L, 0L, 1L, 2L, 2L, 2L, 3L, 3L, 3L, 3L, 3L, 3L),
           c(1L, 2L, 1L, 1L, 2L, 2L, 1L, 1L, 2L, 2L, 2L, 3L),
           c(0L, 1L, 0L, 1L, 0L, 1L, 0L, 0L, 0L, 1L, 1L, 1L))
y <- x
y[2, 1] <- NA_integer_
y[5, 2] <- NA_integer_
y[10, 3] <- NA_integer_
continuous <- cbind(c(-3, 0, 1, 1, 2, 3, 7, 9, 10, 15, 18, 20),
                    c(20, 10, 8, 5, 3, 2, 0, -1, -4, -5, -7, -8))
measure <- function(z, method) c(
    entropy(z, method),
    vapply(seq_len(ncol(z)), function(j) entropy(z[, j], method), numeric(1)),
    condentropy(z[, 1:2], z[, 3, drop = FALSE], method),
    mutinformation(z[, 1, drop = FALSE], z[, 2:3], method),
    condinformation(z[, 1], z[, 2], z[, 3], method),
    multiinformation(z, method), interinformation(z, method),
    as.vector(mutinformation(as.data.frame(z), method = method)))
write_parameter <- function(name, a, type) {
    dimensions <- paste(dim(a), collapse = ', ')
    cat('   ', type, ', parameter :: ', name, '(', dimensions, ') = reshape([ &\n', sep = '')
    v <- as.vector(a)
    for (i in seq_along(v)) {
        value <- if (type == 'integer') {
            if (is.na(v[i])) 'na_integer' else as.character(v[i])
        } else paste0(sprintf('%.17e', v[i]), '_dp')
        tail <- if (i == length(v)) paste0('], [', dimensions, '])\n') else ', &\n'
        cat('      ', value, tail, sep = '')
    }
}
cat('! SPDX-License-Identifier: GPL-3.0-or-later\n')
cat('! Generated by tools/generate_reference.R using actual R infotheo 1.2.0.1.\n')
cat('! Method order: emp, mm, upstream sg (use sg_r in Fortran), shrink.\n')
cat('module r_reference_data\n   use infotheo, only : dp, na_integer\n   implicit none\n')
write_parameter('reference_data', x, 'integer')
write_parameter('missing_data', y, 'integer')
methods <- c('emp', 'mm', 'sg', 'shrink')
write_parameter('reference_values', sapply(methods, function(m) measure(x, m)), 'real(dp)')
write_parameter('missing_values', sapply(methods, function(m) measure(y, m)), 'real(dp)')
write_parameter('continuous_data', continuous, 'real(dp)')
write_parameter('ef_bins', as.matrix(discretize(continuous, 'equalfreq', 5)), 'integer')
write_parameter('ew_bins', as.matrix(discretize(continuous, 'equalwidth', 5)), 'integer')
write_parameter('global_bins', as.matrix(discretize(continuous, 'globalequalwidth', 5)), 'integer')
cat('end module r_reference_data\n')
