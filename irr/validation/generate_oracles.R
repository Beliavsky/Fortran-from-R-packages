# Run from irr: Rscript validation/generate_oracles.R > test/irr_reference.f90
suppressPackageStartupMessages(library(irr))
stopifnot(as.character(packageVersion('irr')) == '0.85')
x <- outer(1:12,1:4,function(i,j) sin(i+j/2)*2+i/4+j/3+cos(i*j)/3)
y <- outer(1:30,1:4,function(i,j) ((i*j+floor(i/3)+j*j) %% 4)+1)
y[,2] <- ifelse((1:30) %% 3==0,y[,2],y[,1])
y[1:4,1] <- 1:4
y[1:4,2] <- 1:4
values <- function(z) c(z$value, z$statistic, z$p.value)
cat('! SPDX-License-Identifier: GPL-2.0-or-later\n! Generated by R 4.5.0, irr 0.85, validation/generate_oracles.R.\n')
cat('module irr_reference\n   use r_kinds, only: dp\n   implicit none\n')
emit <- function(name, z) {
 stopifnot(all(is.finite(z)))
 cat('   real(dp), parameter :: ',name,'(',length(z),') = [ &\n',sep='')
 for(i in seq_along(z)) cat('      ',sprintf('%.17e_dp',z[i]),if(i<length(z))', &' else ' ]','\n',sep='')
}
emit('ref_agree',c(agree(y)$value,agree(y,1)$value))
for(w in c('unweighted','equal','squared')) emit(paste0('ref_kappa_',w),values(kappa2(y[,1:2],w)))
emit('ref_kappa_custom',values(kappa2(y[,1:2],c(0,1,2,5))))
emit('ref_kappa_unsorted',values(kappa2(y[,1:2],c(2,0,5,1))))
emit('ref_fleiss',values(kappam.fleiss(y)))
emit('ref_fleiss_detail',as.vector(kappam.fleiss(y,detail=TRUE)$detail))
emit('ref_fleiss_exact',kappam.fleiss(y,exact=TRUE)$value)
emit('ref_light',suppressWarnings(kappam.light(y)$value))
emit('ref_maxwell',maxwell(y[,1:2] %% 2)$value)
emit('ref_bhapkar',values(bhapkar(y[,1:2])))
emit('ref_rater_bias',values(rater.bias(y[,1:2])))
emit('ref_stuart_maxwell',values(stuart.maxwell.mh(y[,1:2])))
emit('ref_kendall',values(kendall(y)))
emit('ref_kendall_correct',values(kendall(y,TRUE)))
for(fisher in c(TRUE,FALSE)){
 emit(paste0('ref_meancor_',tolower(fisher)),values(meancor(x,fisher)))
 emit(paste0('ref_meanrho_',tolower(fisher)),values(meanrho(y,fisher)))
}
for(model in c('oneway','twoway')){
 emit(paste0('ref_finn_',model),values(finn(x,7,model)))
 for(type in c('consistency','agreement'))for(unit in c('single','average')){
  z<-icc(x,model,type,unit,r0=.3,conf.level=.8)
  emit(paste('ref_icc',model,type,unit,sep='_'),c(z$value,z$Fvalue,z$p.value,z$df1,z$df2,z$lbound,z$ubound))
 }
}
emit('ref_robinson',robinson(x)$value)
emit('ref_iota_quant',iota(list(x,x+matrix(sin(1:48),12,4)))$value)
emit('ref_iota_stand',iota(list(x,x+matrix(sin(1:48),12,4)),standardize=TRUE)$value)
emit('ref_iota_nominal',iota(list(y,y %% 3),scaledata='nominal')$value)
for(method in c('nominal','ordinal','interval','ratio')){
 emit(paste0('ref_alpha_',method),kripp.alpha(t(y),method)$value)
 yy<-t(y)
 yy[1,1]<-NA
 yy[2:4,2]<-NA
 emit(paste0('ref_alpha_missing_',method),kripp.alpha(yy,method)$value)
}
# Listwise deletion fixtures are independent upstream evaluations.
xm <- x
xm[1,1] <- NA
xm[3,4] <- NA
emit('ref_missing_icc',icc(xm,'twoway','agreement')$value)
emit('ref_missing_meancor',values(meancor(xm)))
cat('end module\n')
