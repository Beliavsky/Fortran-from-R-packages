# Run from HDInterval/: Rscript reference/generate_reference.R
# Actual upstream 0.2.4 R functions are retained for reproducibility.
for (f in sort(list.files("upstream/R", full.names = TRUE))) source(f)
stopifnot(read.dcf("upstream/DESCRIPTION")[1, "Version"] == "0.2.4")
values <- list()
add <- function(name, value) values[[name]] <<- as.numeric(value)
add("sample_regular", hdi(c(9, 1, 2, 3, 4, 8, 20), .6))
add("sample_integer_span", hdi(1:5, .6))
add("sample_ties", hdi(c(3, 1, 2, 3, 2, 1, 9), .5))
add("sample_tiny_mass", hdi(c(4, 2, 7), .1))
add("sample_missing", hdi(c(NA, 5, NaN, 1, 2, 8, 10), .6))
add("sample_matrix", hdi(cbind(c(1, 2, 3, 4, 5), c(2, 4, 8, 16, 32)), .6))
x <- -3:3
y <- c(3, 4, 0, 0, 2, 4, 1)
add("density_split", hdi(structure(list(x=x, y=y), class="density"), .6, allowSplit=TRUE))
add("density_joined", suppressWarnings(hdi(structure(list(x=x, y=y), class="density"), .6)))
add("density_height", attr(hdi(structure(list(x=x, y=y), class="density"), .6, allowSplit=TRUE), "height"))
x <- seq(-8, 8, length.out=65)
y <- dnorm(x, -3, .8) + .7 * dnorm(x, 2, 1.1)
add("mixture_grid_x", x)
add("mixture_grid_y", y)
add("mixture_split", hdi(structure(list(x=x, y=y), class="density"), .8, allowSplit=TRUE))
add("mixture_joined", suppressWarnings(hdi(structure(list(x=x, y=y), class="density"), .8)))
add("mixture_height", attr(hdi(structure(list(x=x, y=y), class="density"), .8, allowSplit=TRUE), "height"))
add("function_normal", hdi(qnorm, .95))
add("function_normal_small", hdi(qnorm, .3))
add("function_logistic", hdi(qlogis, .8))
add("function_exponential", hdi(qexp, .95))
add("function_beta21", hdi(qbeta, .8, shape1=2, shape2=1))
add("function_cauchy", hdi(qcauchy, .7))
p <- c(0, 1e-8, .01, .2, .5, .8, .99, 1-1e-8, 1)
add("probabilities", p)
add("inverse_logistic", inverseCDF(p, plogis))
add("inverse_normal", inverseCDF(p, pnorm))
add("inverse_shifted", inverseCDF(c(.1,.5,.9), function(x) plogis(x, location=1000, scale=7)))
add("inverse_cauchy", inverseCDF(c(.01,.5,.99), pcauchy))
writeLines(c("# Actual R 4.5.0 execution of HDInterval 0.2.4; 2026-10-11.",
             paste0(names(values), ": ", vapply(values, function(x) paste(sprintf("%.17g", x), collapse=", "), ""))),
           "reference/expected.txt")
lines <- c("! SPDX-License-Identifier: GPL-3.0-only", "! Generated by reference/generate_reference.R from actual upstream R output.",
           "module r_reference_values", "   use hdinterval, only: dp", "   implicit none")
for (nm in names(values)) {
  v <- values[[nm]]
  lines <- c(lines, sprintf("   real(dp), parameter :: %s(%d) = [ &", nm, length(v)))
  for (i in seq_along(v)) {
    suffix <- if(i == length(v)) "]" else ", &"
    lines <- c(lines, paste0("      ", sprintf("%.17e", v[i]), "_dp", suffix))
  }
}
writeLines(c(lines, "end module r_reference_values"), "test/r_reference_values.f90")
cat("Generated", length(values), "actual-R reference arrays using", R.version.string, "\n")
